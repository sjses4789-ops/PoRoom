// 정보 게시판으로 바꿔치기 — src/lib/supabase/middleware.ts의 rewrite).
// 글 본문이 접혀 있지 않고 전부 펼쳐져 보여서 크롤러가 읽을 콘텐츠가 많다.
// 로그인한 회원은 영향 없이 원래대로 동작한다. 승인 후에는 이 값을 false로
// 바꾸면 소개 홈페이지가 그대로 돌아온다(ADSENSE_REVIEW_MODE와 별개로 끌 수 있다).
