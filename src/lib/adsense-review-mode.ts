// 애드센스 사이트 심사 대응용 임시 스위치.
//
// 구글 애드센스가 "로그인해야 콘텐츠를 확인할 수 있어 검토가 불가능함"을
// 사유로 반려했다 — [포룸](방 목록)·[피드]·[랭킹]·[휴식]·[도전] 목록
// 페이지를 심사(크롤러) 동안만 로그인 없이도 볼 수 있게 열어두기 위한
// 스위치다. [개인]·방 내부·도전 상세·관리자 페이지는 이 값과 무관하게
// 항상 로그인이 필요하다(각 페이지가 스스로 로그인을 요구하도록 따로
// 처리돼 있음).
//
// 이 값을 참조하는 곳은 딱 두 곳뿐이다:
//   - src/lib/supabase/middleware.ts (로그인 리다이렉트를 거를지)
//   - src/app/(main)/layout.tsx (레이아웃 자체의 로그인 리다이렉트를 거를지)
// 애드센스 승인이 나면 이 값을 false로 바꾸기만 하면 즉시 원래대로(로그인
//해야 (main) 전체 접근 가능) 완전히 복구된다 — 되돌리려고 손댈 파일은
// 이 한 줄이 전부다. (콘텐츠 페이지들 자체가 로그인 없이도 안전하게
// 동작하도록 고쳐둔 부분은 되돌릴 필요 없이 그대로 둬도 된다 — 로그인한
// 사용자에게는 원래와 동일하게 동작한다.)
export const ADSENSE_REVIEW_MODE = true;

